class Command(BaseCommand):
    help = "Seed the exercise library used for workout plan generation."

    def handle(self, *args, **options):
        created = 0
        by_name = {}

        for data in EXERCISES:
            exercise, was_created = Exercise.objects.update_or_create(
                name=data["name"],
                defaults=dict(
                    video_url=data.get("video", ""),
                    category=data["category"],
                    movement_type=data["movement_type"],
                    difficulty_level=data["difficulty"],
                    target_muscles=data["muscles"],
                    equipment_required=data["equipment"],
                    primary_goal_tags=data["goals"],
                    instructions=data["instructions"],
                    breathing_guidance=data["breathing"],
                    common_mistakes=data["mistakes"],
                    default_rest_seconds=data["rest"],
                    default_sets=data["sets"],
                    default_reps=data["reps"],
                    default_hold_seconds=data["hold"],
                ),
            )
            by_name[data["name"]] = exercise
            created += int(was_created)

        for data in EXERCISES:
            exercise = by_name[data["name"]]
            easier_name = data.get("easier")
            harder_name = data.get("harder")
            changed = False
            if easier_name and by_name.get(easier_name):
                exercise.easier_variation = by_name[easier_name]
                changed = True
            if harder_name and by_name.get(harder_name):
                exercise.harder_variation = by_name[harder_name]
                changed = True
            if changed:
                exercise.save()

        self.stdout.write(self.style.SUCCESS(f"Seeded {created} new exercises ({len(EXERCISES)} total in library)."))
